-- O VIAJANTE — walk LESTE, 4 frames, poses reais:
-- f1 CONTACT (perna da frente estendida à direita, de trás no calcanhar),
-- f2 RECOIL (juntas, corpo baixo +1), f3 PASSING (juntas, alto -1),
-- f4 CONTACT oposto. Braço de trás balança ±2px; aba do casaco balança;
-- arco firme na mão da frente. viajante_walk_w = espelho via código.

local function L(s)
    assert(#s <= 64, 'linha de sprite > 64 colunas')
    return s .. string.rep('.', 64 - #s)
end
local E = string.rep('.', 64)
local function R(map)
    local t = {}
    for r = 1, 96 do
        local s = map[r]
        t[r] = s and L(s) or E
    end
    return table.concat(t, '\n')
end
local function shift(map, dy, rmin, rmax)
    local t = {}
    for r, s in pairs(map) do
        if rmin and r >= rmin and r <= rmax and s then t[r + dy] = s
        else t[r] = s end
    end
    return t
end
-- desloca conteúdo horizontalmente dentro das linhas [rmin..rmax]
local function hshift(map, dx, rmin, rmax)
    local t = {}
    for r, s in pairs(map) do
        if rmin and r >= rmin and r <= rmax and s then
            if dx > 0 then t[r] = string.rep('.', dx) .. s
            else t[r] = s:sub(-dx + 1) end
        else t[r] = s end
    end
    return t
end
local function overlay(ga, gb)
    local A, B, out = {}, {}, {}
    for l in ga:gmatch('[^\n]+') do A[#A + 1] = l end
    for l in gb:gmatch('[^\n]+') do B[#B + 1] = l end
    for i = 1, #A do
        local a, b, row = A[i], B[i] or '', {}
        for x = 1, 64 do
            local cb = b:sub(x, x)
            row[x] = (cb ~= '.' and cb ~= ' ' and cb ~= '') and cb
                or a:sub(x, x)
        end
        out[i] = table.concat(row)
    end
    return table.concat(out, '\n')
end

