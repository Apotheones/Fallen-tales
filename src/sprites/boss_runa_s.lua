-- RUNA (boss_runa_s) — a vigia da grade, chefe 1 da campanha, duelo na
-- Colina. 64x96, origem nos pés, 3 frames: [idle1, idle2] respiração,
-- [3] WARN = mira com a lança (nivelada à altura do peito).
-- Âncoras (docs/PERSONAGENS_DIRECAO_VISUAL_E_NARRATIVA.md §9):
--   manto triangular curto (verde seco 'm', forro palha 'l') |
--   trança ruiva baixa ('a'/'A' rust) caída no ombro esquerdo |
--   polainas claras ('P'/'O' bone) marcando as canelas.
-- Roupa para o frio que sobe do chão: camisa carvão 'i', proteção de
-- couro castanho 'L' com correias 'x', lança curta 'w'/'T' da vigia,
-- molho de chaves 'g' no cinto. Pele bege rosada 's' com sardas 'd',
-- olhos verde-acinzentado 'y'. Pessoa, não constructo — sem outline de
-- pedra, sem emissivo de eco; a presença é de postura, não de canvas.
--
--   0123456789 123456789 123456789 123456789 123456789 123456789 1234
local function L(s)
    assert(#s <= 64, 'linha de sprite > 64 colunas')
    return s .. string.rep('.', 64 - #s)
end
local E = string.rep('.', 64)
local function R(map)
    local t = {}
    for r = 1, 96 do
        local s = map[r]
        t[r] = s and L(s) or E
    end
    return table.concat(t, '\n')
end
local function shift(map, dy, rmin, rmax)
    local t = {}
    for r, s in pairs(map) do
        if rmin and r >= rmin and r <= rmax then t[r + dy] = s
        else t[r] = s end
    end
    return t
end

