-- VIGIA DOS ECOS (foe_watcher) — eco marcador dos sepultados, 64x96,
-- origem nos pés. Build 'needle' das devotas legadas: coluna fina de
-- pano violeta sobre pernas-palito de pedra, capuz agulha sobre máscara
-- de osso miúda. Ao lado direito carrega o MARCO do ofício: bastão de
-- osso plantado no chão encimado por uma cruz-sigilo 'x' — é essa cruz
-- que ele acende sob quem se aproxima.
-- Frames: [1,2] idle (respiração: robe e cabeça descem 1px, bastão
-- acompanha), [3] WARN = ergue o bastão para marcar: o sigilo 'X' e os
-- olhos acendem e a cruz da marca já brilha no chão sob a ponta.
--
--   0123456789 123456789 123456789 123456789 123456789 123456789 1234
local function L(s)
    assert(#s <= 64, 'linha de sprite > 64 colunas')
    return s .. string.rep('.', 64 - #s)
end
local E = string.rep('.', 64)
local function R(map)
    local t = {}
    for r = 1, 96 do
        local s = map[r]
        t[r] = s and L(s) or E
    end
    return table.concat(t, '\n')
end
local function shift(map, dy, rmin, rmax)
    local t = {}
    for r, s in pairs(map) do
        if rmin and r >= rmin and r <= rmax then t[r + dy] = s
        else t[r] = s end
    end
    return t
end

