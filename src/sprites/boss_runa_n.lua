-- RUNA (boss_runa_n) — a vigia, de costas. 64x96, origem nos pés,
-- 3 frames: [idle1, idle2] respiração, [3] WARN = lança nivelada.
-- De costas o que lê é: massa de cabelo ruivo cobrindo a cabeça, trança
-- baixa descendo pelo centro das costas sobre o manto triangular, forro
-- palha na borda, polainas claras, lança na mão direita.
-- Mesma legend do _s.
--
--   0123456789 123456789 123456789 123456789 123456789 123456789 1234
local function L(s)
    assert(#s <= 64, 'linha de sprite > 64 colunas')
    return s .. string.rep('.', 64 - #s)
end
local E = string.rep('.', 64)
local function R(map)
    local t = {}
    for r = 1, 96 do
        local s = map[r]
        t[r] = s and L(s) or E
    end
    return table.concat(t, '\n')
end
local function shift(map, dy, rmin, rmax)
    local t = {}
    for r, s in pairs(map) do
        if rmin and r >= rmin and r <= rmax then t[r + dy] = s
        else t[r] = s end
    end
    return t
end

