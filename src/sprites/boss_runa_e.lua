-- RUNA (boss_runa_e) — a vigia, perfil leste (olhando à direita).
-- 64x96, origem nos pés, 3 frames: [idle1, idle2] respiração,
-- [3] WARN = lança nivelada para a frente (o perfil é onde a mira lê
-- melhor: haste horizontal, ponta para a direita, as duas mãos nela).
-- boss_runa_w = espelho por código (como viajante_w).
-- Âncoras mantidas: manto triangular (aba de trás a cair na nuca/ombro
-- de trás, ponta curta à frente), trança ruiva baixa nas costas,
-- polainas claras nas duas canelas (perto 'P' / longe 'F' mais escura).
--
--   0123456789 123456789 123456789 123456789 123456789 123456789 1234
local function L(s)
    assert(#s <= 64, 'linha de sprite > 64 colunas')
    return s .. string.rep('.', 64 - #s)
end
local E = string.rep('.', 64)
local function R(map)
    local t = {}
    for r = 1, 96 do
        local s = map[r]
        t[r] = s and L(s) or E
    end
    return table.concat(t, '\n')
end
local function shift(map, dy, rmin, rmax)
    local t = {}
    for r, s in pairs(map) do
        if rmin and r >= rmin and r <= rmax then t[r + dy] = s
        else t[r] = s end
    end
    return t
end

