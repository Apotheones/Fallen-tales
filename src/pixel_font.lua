local accents = {
    ['Á']={'A','00100','01000'}, ['À']={'A','01000','00100'}, ['Â']={'A','00100','01010'}, ['Ã']={'A','01010','10100'},
    ['É']={'E','00100','01000'}, ['Ê']={'E','00100','01010'}, ['Í']={'I','001','010'},
